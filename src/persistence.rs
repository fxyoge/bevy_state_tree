//! Backend-independent, versioned checkpoints. Enable the `persistence` feature.
//!
//! Domains and built-ins register themselves. Games register ordinary serializable
//! resources/components with [`AppPersistenceExt`]; there are no activity-specific
//! save callbacks. Entity fields use [`entity`], and activity tokens are automatic,
//! including tokens used as map keys. Capture after domain schedules and their
//! activity/effect handlers have finished; apply schedule-owned commands first.
//!
//! [`Checkpoint`] is an owned Serde value, independent of file formats and storage
//! engines. Restore replaces the selected entities and registered resources. All
//! definitions must be loaded first; unavailable assets are requested and restore
//! can be retried. Decode/compatibility failures leave existing game state intact.
//!
//! ```no_run
//! use bevy_app::App;
//! use bevy_ecs::prelude::*;
//! use bevy_state_tree::persistence::{AppPersistenceExt, Checkpoint};
//! use serde::{Deserialize, Serialize};
//!
//! #[derive(Resource, Serialize, Deserialize)]
//! struct GameProgress { score: u64 }
//!
//! let mut app = App::new(); // Install your usual asset/time/state-tree plugins.
//! app.insert_resource(GameProgress { score: 12 })
//!     .persist_resource::<GameProgress>("game-progress");
//! let checkpoint = Checkpoint::capture(app.world_mut())?;
//! // Send this owned Serde value to any storage backend.
//! let bytes = serde_json::to_vec(&checkpoint)?;
//! serde_json::from_slice::<Checkpoint>(&bytes)?.restore(app.world_mut())?;
//! # Ok::<(), Box<dyn std::error::Error>>(())
//! ```
//!
//! All persistent activity progress must be in registered ordinary game data.
//! Tokens require no field annotations; entity references require [`entity`] or
//! [`optional_entity`]. Event payload codecs are generated by `StateTreeEvent`;
//! their other fields, and global binding configurations/values, must be ordinary
//! serializable owned data. Custom handwritten event implementations need a codec
//! only if their events can be pending at capture. Checkpoints validate an exact
//! definition fingerprint; authored-content migration is not implicit.

