pub(crate) type Apply = Box<dyn FnOnce(&mut World)>;

#[derive(Debug, thiserror::Error)]
pub enum Error {
    #[error("invalid checkpoint: {0}")]
    Invalid(String),
    #[error("checkpoint data: {0}")]
    Data(String),
    #[error("definition is not loaded: {0}")]
    DefinitionNotLoaded(String),
}

impl From<serde_json::Error> for Error {
    fn from(value: serde_json::Error) -> Self {
        Self::Data(value.to_string())
    }
}

pub(crate) fn invalid(message: impl Into<String>) -> Error {
    Error::Invalid(message.into())
}

/// An owned checkpoint of all installed domains and registered game data.
/// Serialize it with the storage format of your choice.
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct Checkpoint {
    version: u32,
    entities: usize,
    runs: Vec<RunReference>,
    domains: BTreeMap<String, DomainSnapshot>,
    data: BTreeMap<String, Vec<u8>>,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub(crate) struct RunReference {
    pub owner: usize,
    pub domain: String,
    pub activity: u32,
    pub generation: u64,
    pub activity_type: String,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub(crate) struct DomainSnapshot {
    pub trees: Vec<TreeSnapshot>,
    pub broadcasts: Vec<SavedEvent>,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub(crate) struct TreeSnapshot {
    pub owner: usize,
    pub disabled: bool,
    pub definition: String,
    pub path: Option<String>,
    pub fingerprint: Option<[u8; 32]>,
    pub runtime: crate::instance::persistence::RuntimeSnapshot,
    pub events: Vec<(usize, SavedEvent)>,
    pub outcomes: Vec<SavedOutcome>,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub(crate) struct SavedEvent {
    pub name: String,
    pub payload: Vec<u8>,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub(crate) struct SavedOutcome {
    pub run: usize,
    pub success: bool,
    pub data: Result<Option<Value>, String>,
}

// Keep Luau's integer/number distinction and every floating-point bit pattern.
// The shared engine deliberately has no dependency on a persistence backend.
#[derive(Clone, Debug, Serialize, Deserialize)]
pub(crate) enum Value {
    Nil,
    Boolean(bool),
    Integer(i64),
    Number(u64),
    String(String),
    Sequence(Vec<Value>),
    Record(BTreeMap<String, Value>),
}

impl From<&crate::LuauValue> for Value {
    fn from(value: &crate::LuauValue) -> Self {
        use crate::LuauValue as L;
        match value {
            L::Nil => Self::Nil,
            L::Boolean(v) => Self::Boolean(*v),
            L::Integer(v) => Self::Integer(*v),
            L::Number(v) => Self::Number(v.to_bits()),
            L::String(v) => Self::String(v.clone()),
            L::Sequence(v) => Self::Sequence(v.iter().map(Self::from).collect()),
            L::Record(v) => {
                Self::Record(v.iter().map(|(k, v)| (k.clone(), Self::from(v))).collect())
            }
        }
    }
}

impl From<Value> for crate::LuauValue {
    fn from(value: Value) -> Self {
        match value {
            Value::Nil => Self::Nil,
            Value::Boolean(v) => Self::Boolean(v),
            Value::Integer(v) => Self::Integer(v),
            Value::Number(v) => Self::Number(f64::from_bits(v)),
            Value::String(v) => Self::String(v),
            Value::Sequence(v) => Self::Sequence(v.into_iter().map(Self::from).collect()),
            Value::Record(v) => {
                Self::Record(v.into_iter().map(|(k, v)| (k, Self::from(v))).collect())
            }
        }
    }
}

#[derive(Clone)]
pub(crate) struct ResolvedRun {
    pub token: ErasedActivityToken,
    pub domain: String,
    pub activity_type: String,
}

enum Session {
    Save {
        entities: HashMap<Entity, usize>,
        runs: HashMap<ErasedActivityToken, usize>,
    },
    Load {
        entities: Vec<Entity>,
        runs: Vec<ResolvedRun>,
    },
}

thread_local! { static SESSION: RefCell<Option<Session>> = const { RefCell::new(None) }; }

fn scope<T>(session: Session, f: impl FnOnce() -> Result<T, Error>) -> Result<T, Error> {
    if SESSION.with(|s| s.borrow().is_some()) {
        return Err(invalid("nested persistence session"));
    }
    struct Guard;
    impl Drop for Guard {
        fn drop(&mut self) {
            SESSION.with(|s| s.replace(None));
        }
    }
    SESSION.with(|s| s.replace(Some(session)));
    let _guard = Guard;
    f()
}

pub(crate) fn entity_id(entity: Entity) -> Result<usize, Error> {
    SESSION.with(|s| match s.borrow().as_ref() {
        Some(Session::Save { entities, .. }) => entities
            .get(&entity)
            .copied()
            .ok_or_else(|| invalid("entity reference points outside the checkpoint selection")),
        _ => Err(invalid(
            "entity serialization requires a checkpoint capture session",
        )),
    })
}

pub(crate) fn loaded_entity(id: usize) -> Result<Entity, Error> {
    SESSION.with(|s| match s.borrow().as_ref() {
        Some(Session::Load { entities, .. }) => entities
            .get(id)
            .copied()
            .ok_or_else(|| invalid("dangling entity reference")),
        _ => Err(invalid(
            "entity deserialization requires a checkpoint restore session",
        )),
    })
}

pub(crate) fn run_id(token: ErasedActivityToken) -> Result<usize, Error> {
    SESSION.with(|s| match s.borrow().as_ref() {
        Some(Session::Save { runs, .. }) => runs
            .get(&token)
            .copied()
            .ok_or_else(|| invalid("activity token does not identify a saved live run")),
        _ => Err(invalid(
            "token serialization requires a checkpoint capture session",
        )),
    })
}

pub(crate) fn loaded_run(id: usize) -> Result<ResolvedRun, Error> {
    SESSION.with(|s| match s.borrow().as_ref() {
        Some(Session::Load { runs, .. }) => runs
            .get(id)
            .cloned()
            .ok_or_else(|| invalid("dangling activity run reference")),
        _ => Err(invalid(
            "token deserialization requires a checkpoint restore session",
        )),
    })
}

impl<D: StateTreeDomain, A: StateTreeActivity> Serialize for StateTreeActivityToken<D, A> {
    fn serialize<S: Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        serializer.serialize_u64(run_id(self.erased()).map_err(serde::ser::Error::custom)? as u64)
    }
}

impl<'de, D: StateTreeDomain, A: StateTreeActivity> Deserialize<'de>
    for StateTreeActivityToken<D, A>
{
    fn deserialize<S: Deserializer<'de>>(deserializer: S) -> Result<Self, S::Error> {
        let id = usize::deserialize(deserializer)?;
        let run = loaded_run(id).map_err(serde::de::Error::custom)?;
        if run.domain != D::AUTHORED_NAME || run.activity_type != type_name::<A>() {
            return Err(serde::de::Error::custom(
                "activity run domain/type mismatch",
            ));
        }
        Ok(run.token.typed())
    }
}

/// `#[serde(with = "bevy_state_tree::persistence::entity")]` for entity fields.
/// Unlike raw Bevy entity bits these references survive loading into another world.
pub mod entity {
    use super::*;
    pub fn serialize<S: Serializer>(entity: &Entity, serializer: S) -> Result<S::Ok, S::Error> {
        serializer.serialize_u64(entity_id(*entity).map_err(serde::ser::Error::custom)? as u64)
    }
    pub fn deserialize<'de, D: Deserializer<'de>>(deserializer: D) -> Result<Entity, D::Error> {
        loaded_entity(usize::deserialize(deserializer)?).map_err(serde::de::Error::custom)
    }
}

/// Entity-reference adapter for `Option<Entity>` fields.
pub mod optional_entity {
    use super::*;
    pub fn serialize<S: Serializer>(
        value: &Option<Entity>,
        serializer: S,
    ) -> Result<S::Ok, S::Error> {
        value
            .map(entity_id)
            .transpose()
            .map_err(serde::ser::Error::custom)?
            .serialize(serializer)
    }
    pub fn deserialize<'de, D: Deserializer<'de>>(
        deserializer: D,
    ) -> Result<Option<Entity>, D::Error> {
        Option::<usize>::deserialize(deserializer)?
            .map(loaded_entity)
            .transpose()
            .map_err(serde::de::Error::custom)
    }
}

/// Serde field adapter for the shared engine's `LuauValue`. It preserves numeric
/// type and floating-point bits, including negative zero and nonfinite values.
pub mod luau_value {
    use super::*;
    pub fn serialize<S: Serializer>(
        value: &crate::LuauValue,
        serializer: S,
    ) -> Result<S::Ok, S::Error> {
        Value::from(value).serialize(serializer)
    }
    pub fn deserialize<'de, D: Deserializer<'de>>(
        deserializer: D,
    ) -> Result<crate::LuauValue, D::Error> {
        Ok(Value::deserialize(deserializer)?.into())
    }
}

pub(crate) trait DomainCodec: Send + Sync {
    fn entities(&self, world: &mut World) -> Vec<Entity>;
    fn runs(&self, world: &mut World) -> Vec<(ErasedActivityToken, &'static str)>;
    fn capture(&self, world: &mut World) -> Result<DomainSnapshot, Error>;
    fn prepare(
        &self,
        world: &mut World,
        snapshot: &DomainSnapshot,
        entities: &[Entity],
    ) -> Result<(Apply, Vec<ResolvedRun>, Vec<u64>), Error>;
    fn prepare_ingress(
        &self,
        world: &World,
        snapshot: &DomainSnapshot,
        entities: &[Entity],
        runtimes: &[u64],
    ) -> Result<Apply, Error>;
    fn clear(&self, world: &mut World);
}

pub(crate) trait DataCodec: Send + Sync {
    fn codec_type(&self) -> &'static str {
        type_name::<Self>()
    }
    fn entities(&self, _world: &mut World) -> Vec<Entity> {
        Vec::new()
    }
    fn capture(&self, world: &mut World) -> Result<Vec<u8>, Error>;
    fn prepare(&self, world: &World, bytes: &[u8]) -> Result<Apply, Error>;
}

#[derive(Resource, Default)]
pub(crate) struct Registry {
    pub domains: BTreeMap<String, Arc<dyn DomainCodec>>,
    pub data: BTreeMap<String, Arc<dyn DataCodec>>,
}

/// Registers normal game data, not activity adapters. Keys are stable on-disk
/// schema identifiers. Fields referencing entities use [`entity`].
pub trait AppPersistenceExt {
    fn persist_resource<T: Resource + Serialize + DeserializeOwned>(
        &mut self,
        key: &str,
    ) -> &mut Self;
    fn persist_component<T: Component + Serialize + DeserializeOwned>(
        &mut self,
        key: &str,
    ) -> &mut Self;
}

impl AppPersistenceExt for App {
    fn persist_resource<T: Resource + Serialize + DeserializeOwned>(
        &mut self,
        key: &str,
    ) -> &mut Self {
        register_data(self, key, Arc::new(ResourceCodec::<T>(PhantomData)));
        self
    }
    fn persist_component<T: Component + Serialize + DeserializeOwned>(
        &mut self,
        key: &str,
    ) -> &mut Self {
        register_data(self, key, Arc::new(ComponentCodec::<T>(PhantomData)));
        self
    }
}

pub(crate) fn register_data(app: &mut App, key: &str, codec: Arc<dyn DataCodec>) {
    assert!(!key.is_empty(), "persistence keys cannot be empty");
    app.init_resource::<Registry>();
    let mut registry = app.world_mut().resource_mut::<Registry>();
    assert!(
        !registry.data.contains_key(key),
        "duplicate persistence key: {key}"
    );
    assert!(
        !registry
            .data
            .values()
            .any(|registered| registered.codec_type() == codec.codec_type()),
        "type is already registered for persistence: {}",
        codec.codec_type()
    );
    registry.data.insert(key.into(), codec);
}

pub(crate) fn query_all<Q: bevy_ecs::query::QueryData, F: bevy_ecs::query::QueryFilter>(
    world: &mut World,
) -> bevy_ecs::query::QueryState<Q, F> {
    use bevy_ecs::entity_disabling::DefaultQueryFilters;
    if world.contains_resource::<DefaultQueryFilters>() {
        world.resource_scope(|world, _: Mut<DefaultQueryFilters>| world.query_filtered::<Q, F>())
    } else {
        world.query_filtered::<Q, F>()
    }
}

struct ResourceCodec<T>(PhantomData<T>);

#[derive(Serialize, Deserialize)]
enum SavedResource<T> {
    Absent,
    Present(T),
}

impl<T: Resource + Serialize + DeserializeOwned> DataCodec for ResourceCodec<T> {
    fn capture(&self, world: &mut World) -> Result<Vec<u8>, Error> {
        let value = match world.get_resource::<T>() {
            Some(value) => SavedResource::Present(value),
            None => SavedResource::Absent,
        };
        Ok(serde_json::to_vec(&value)?)
    }
    fn prepare(&self, _world: &World, bytes: &[u8]) -> Result<Apply, Error> {
        let value: SavedResource<T> = serde_json::from_slice(bytes)?;
        Ok(Box::new(move |world| match value {
            SavedResource::Present(value) => {
                world.insert_resource(value);
            }
            SavedResource::Absent => {
                world.remove_resource::<T>();
            }
        }))
    }
}

struct ComponentCodec<T>(PhantomData<T>);
impl<T: Component + Serialize + DeserializeOwned> DataCodec for ComponentCodec<T> {
    fn entities(&self, world: &mut World) -> Vec<Entity> {
        query_all::<Entity, With<T>>(world).iter(world).collect()
    }
    fn capture(&self, world: &mut World) -> Result<Vec<u8>, Error> {
        let values = query_all::<(Entity, &T), ()>(world)
            .iter(world)
            .map(|(entity, value)| Ok((entity_id(entity)?, value)))
            .collect::<Result<Vec<_>, Error>>()?;
        Ok(serde_json::to_vec(&values)?)
    }
    fn prepare(&self, _world: &World, bytes: &[u8]) -> Result<Apply, Error> {
        let values: Vec<(usize, T)> = serde_json::from_slice(bytes)?;
        let mut seen = HashSet::new();
        let values = values
            .into_iter()
            .map(|(id, value)| {
                if !seen.insert(id) {
                    return Err(invalid("duplicate component owner"));
                }
                Ok((loaded_entity(id)?, value))
            })
            .collect::<Result<Vec<_>, Error>>()?;
        Ok(Box::new(move |world| {
            for (entity, value) in values {
                world.entity_mut(entity).insert(value);
            }
        }))
    }
}

impl Checkpoint {
    /// Captures all domains and registered game data at a completed schedule
    /// boundary. This does not execute game systems or replay effects.
    pub fn capture(world: &mut World) -> Result<Self, Error> {
        world.flush();
        let registry = world
            .get_resource::<Registry>()
            .ok_or_else(|| invalid("no persistence registrations"))?;
        let domains = registry.domains.clone();
        let codecs = registry.data.clone();
        let mut selected = HashSet::new();
        for codec in domains.values() {
            selected.extend(codec.entities(world));
        }
        for codec in codecs.values() {
            selected.extend(codec.entities(world));
        }
        let mut entities: Vec<_> = selected.into_iter().collect();
        entities.sort();
        let entities: HashMap<_, _> = entities
            .into_iter()
            .enumerate()
            .map(|(i, e)| (e, i))
            .collect();
        let mut runs = Vec::new();
        let mut tokens = HashMap::new();
        for (domain, codec) in &domains {
            for (token, activity_type) in codec.runs(world) {
                let id = runs.len();
                tokens.insert(token, id);
                runs.push(RunReference {
                    owner: entities[&token.entity],
                    domain: domain.clone(),
                    activity: token.activity.0,
                    generation: token.generation,
                    activity_type: activity_type.into(),
                });
            }
        }
        let entity_count = entities.len();
        scope(
            Session::Save {
                entities,
                runs: tokens,
            },
            || {
                let domains = domains
                    .iter()
                    .map(|(key, codec)| Ok((key.clone(), codec.capture(world)?)))
                    .collect::<Result<_, Error>>()?;
                let data = codecs
                    .iter()
                    .map(|(key, codec)| Ok((key.clone(), codec.capture(world)?)))
                    .collect::<Result<_, Error>>()?;
                Ok(Self {
                    version: 1,
                    entities: entity_count,
                    runs,
                    domains,
                    data,
                })
            },
        )
    }

    /// Restores without re-entering states or restarting consumers' saved runs.
    /// Assets must already be loaded. Registered game state is decoded before
    /// existing entities are removed. Unselected world state is retained.
    pub fn restore(&self, world: &mut World) -> Result<(), Error> {
        if self.version != 1 {
            return Err(invalid("unsupported checkpoint version"));
        }
        world.flush();
        let registry = world
            .get_resource::<Registry>()
            .ok_or_else(|| invalid("no persistence registrations"))?;
        let domains = registry.domains.clone();
        let codecs = registry.data.clone();
        if !domains.keys().eq(self.domains.keys()) || !codecs.keys().eq(self.data.keys()) {
            return Err(invalid(
                "checkpoint schema does not match registered domains/data",
            ));
        }
        let mut old = HashSet::new();
        for codec in domains.values() {
            old.extend(codec.entities(world));
        }
        for codec in codecs.values() {
            old.extend(codec.entities(world));
        }
        // Allocate empty destinations while the old selection is still alive.
        // A failed preparation removes only these empties, never live game data.
        let entities: Vec<_> = (0..self.entities)
            .map(|_| world.spawn_empty().id())
            .collect();
        let prepared = (|| {
            let mut apply = Vec::new();
            let mut live = HashMap::new();
            let mut runtime_ids = BTreeMap::new();
            for (key, codec) in &domains {
                let (prepared, runs, runtimes) =
                    codec.prepare(world, &self.domains[key], &entities)?;
                runtime_ids.insert(key.clone(), runtimes);
                apply.push(prepared);
                for run in runs {
                    let key = (
                        run.domain.clone(),
                        run.token.entity,
                        run.token.activity.0,
                        run.token.generation,
                    );
                    if live.insert(key, run).is_some() {
                        return Err(invalid("duplicate restored activity"));
                    }
                }
            }
            let mut seen = HashSet::new();
            let runs = self
                .runs
                .iter()
                .map(|reference| {
                    let entity = *entities
                        .get(reference.owner)
                        .ok_or_else(|| invalid("invalid run owner"))?;
                    let key = (
                        reference.domain.clone(),
                        entity,
                        reference.activity,
                        reference.generation,
                    );
                    if !seen.insert(key.clone()) {
                        return Err(invalid("duplicate activity run reference"));
                    }
                    let run = live
                        .get(&key)
                        .ok_or_else(|| invalid("reference to an inactive activity"))?;
                    if run.activity_type != reference.activity_type {
                        return Err(invalid("activity type changed"));
                    }
                    Ok(run.clone())
                })
                .collect::<Result<Vec<_>, Error>>()?;
            if runs.len() != live.len() {
                return Err(invalid("missing activity run reference"));
            }
            scope(
                Session::Load {
                    entities: entities.clone(),
                    runs,
                },
                || {
                    for (key, codec) in &codecs {
                        apply.push(codec.prepare(world, &self.data[key])?);
                    }
                    // Event payloads/outcomes also use the same reference session.
                    for (key, codec) in &domains {
                        apply.push(codec.prepare_ingress(
                            world,
                            &self.domains[key],
                            &entities,
                            &runtime_ids[key],
                        )?);
                    }
                    Ok(apply)
                },
            )
        })();
        let apply = match prepared {
            Ok(value) => value,
            Err(error) => {
                for entity in entities {
                    world.despawn(entity);
                }
                return Err(error);
            }
        };
        for entity in old {
            world.despawn(entity);
        }
        world.flush();
        for codec in domains.values() {
            codec.clear(world);
        }
        for apply in apply {
            apply(world);
        }
        world.flush();
        Ok(())
    }
}

