#!/usr/bin/env bash
set -euo pipefail

readonly base_url="https://www.w3.org/Voice/2013/scxml-irp"
readonly manifest_snapshot_url="https://web.archive.org/web/20240815160633id_/https://www.w3.org/Voice/2013/scxml-irp/manifest.xml"
readonly mirror_commit="11013b76a02d1534c7375a70f77efd2463798ddd"
readonly mirror_archive="https://github.com/tklab-tud/uscxml/archive/$mirror_commit.tar.gz"
readonly repository_root="$(git rev-parse --show-toplevel)"
readonly suite_root="$repository_root/tests/w3c"
readonly vendor_root="$suite_root/vendor"
readonly staging_root="$(mktemp -d)"
readonly curl_args=(
  --fail
  --location
  --silent
  --show-error
  --retry 12
  --retry-all-errors
  --retry-delay 2
  --user-agent "bevy_state_tree W3C suite importer"
)

trap 'rm -rf "$staging_root"' EXIT

mkdir -p "$staging_root/vendor"
curl "${curl_args[@]}" \
  "$manifest_snapshot_url" \
  --output "$staging_root/vendor/manifest.xml"

perl -nle 'while (/<(?:start|dep)\s+uri="([^"]+)"/g) { print $1 }' \
  "$staging_root/vendor/manifest.xml" \
  | LC_ALL=C sort -u \
  > "$staging_root/resources.txt"

curl "${curl_args[@]}" "$mirror_archive" --output "$staging_root/uscxml.tar.gz"
mkdir -p "$staging_root/uscxml"
tar -xzf "$staging_root/uscxml.tar.gz" --strip-components=1 -C "$staging_root/uscxml"

declare -A resource_by_basename=()
while IFS= read -r resource; do
  if [[ -z "$resource" || "$resource" == /* || "$resource" == *".."* ]]; then
    printf 'refusing unsafe manifest resource: %s\n' "$resource" >&2
    exit 1
  fi
  basename="$(basename "$resource")"
  if [[ -n "${resource_by_basename[$basename]:-}" ]]; then
    printf 'flattened mirror cannot distinguish %s and %s\n' \
      "${resource_by_basename[$basename]}" "$resource" >&2
    exit 1
  fi
  resource_by_basename[$basename]="$resource"
  mkdir -p "$staging_root/vendor/$(dirname "$resource")"
  mirror_resource="$staging_root/uscxml/test/w3c/txml/$basename"
  if [[ ! -f "$mirror_resource" ]]; then
    printf 'pinned mirror is missing manifest resource: %s\n' "$resource" >&2
    exit 1
  fi
  cp "$mirror_resource" "$staging_root/vendor/$resource"
done < "$staging_root/resources.txt"

for stylesheet in confEcma.xsl confXPath.xsl; do
  cp "$staging_root/uscxml/test/w3c/$stylesheet" "$staging_root/vendor/$stylesheet"
done

mkdir -p "$vendor_root"
rm -rf "$vendor_root"
mv "$staging_root/vendor" "$vendor_root"

{
  printf '# Generated by scripts/update-w3c-suite.sh.\n'
  printf '# Review all corpus changes before committing this file.\n'
  printf 'base_url = "%s"\n\n' "$base_url"
  printf 'manifest_snapshot_url = "%s"\n' "$manifest_snapshot_url"
  printf 'payload_mirror = "https://github.com/tklab-tud/uscxml"\n'
  printf 'payload_mirror_commit = "%s"\n\n' "$mirror_commit"
  printf '[[files]]\n'
  (
    cd "$vendor_root"
    find . -type f -print0 \
      | LC_ALL=C sort -z \
      | while IFS= read -r -d '' path; do
          path="${path#./}"
          digest="$(sha256sum "$path" | cut -d ' ' -f 1)"
          bytes="$(wc -c < "$path" | tr -d ' ')"
          printf 'path = "%s"\nsha256 = "%s"\nbytes = %s\n\n[[files]]\n' \
            "$path" "$digest" "$bytes"
        done
  )
} > "$suite_root/vendor.lock.toml"

# Remove the trailing empty table emitted by the simple streaming formatter.
perl -0pi -e 's/\n\[\[files\]\]\n\z/\n/' "$suite_root/vendor.lock.toml"
perl -0pi -e 's/\n+\z/\n/' "$suite_root/vendor.lock.toml"

printf 'Vendored %s W3C resources.\n' "$(find "$vendor_root" -type f | wc -l | tr -d ' ')"
